'use strict';
const express = require('express');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

module.exports = function createInstallRouter(ctx) {
  const { store, config } = ctx;
  const router = express.Router();

  /** سكربت تثبيت مخصص بالإعدادات الحالية + عنوان هذه اللوحة */
  router.get('/install.sh', (req, res) => {
    const tplPath = path.join(config.ROOT, 'scripts', 'install-wireguard.sh');
    let tpl;
    try { tpl = fs.readFileSync(tplPath, 'utf8'); }
    catch { return res.status(500).type('text/plain').send('تعذر قراءة قالب سكربت التثبيت'); }

    const s = store.data.settings;
    const host = String(req.get('x-forwarded-host') || req.get('host') || 'localhost').split(',')[0].trim();
    const proto = String(req.get('x-forwarded-proto') || req.protocol || 'http').split(',')[0].trim();
    const origin = `${proto}://${host}`;
    const header = [
      '# Generated by Saudia VPN Panel — ' + origin,
      `export WG_PORT="\${WG_PORT:-${s.wgPort}}"`,
      `export PANEL_PORT="\${PANEL_PORT:-${config.PORT}}"`,
      `export CLIENT_DNS="\${CLIENT_DNS:-${s.dns}}"`,
      `export WG_NET="\${WG_NET:-${s.network}}"`,
      `export WG_ADDR="\${WG_ADDR:-${s.serverAddress}}"`,
      `export PANEL_URL="\${PANEL_URL:-${origin}}"`,
      ''
    ].join('\n');
    const script = tpl.replace(/^(#!.*\n)/, `$1${header}`);

    res.type('text/x-shellscript; charset=utf-8')
      .set('Content-Disposition', 'attachment; filename="saudia-vpn-install.sh"')
      .send(script);
  });

  /** حزمة اللوحة كاملة (بدون بيانات أو أسرار) لينزّلها السكربت على الخادم السعودي */
  router.get('/panel.tar.gz', (req, res) => {
    const tmp = path.join(os.tmpdir(), `saudia-panel-${Date.now()}.tar.gz`);
    try {
      execFileSync('tar', [
        '--exclude=node_modules', '--exclude=data', '--exclude=.git',
        '--exclude=.env', '--exclude=*.log',
        '-czf', tmp, '-C', config.ROOT, '.'
      ], { timeout: 30000 });
    } catch (e) {
      return res.status(500).json({ error: 'تعذر إنشاء حزمة اللوحة: ' + e.message });
    }
    res.sendFile(tmp, (err) => {
      try { fs.unlinkSync(tmp); } catch { /* ignore */ }
      if (err && !res.headersSent) res.status(500).end();
    });
  });

  return router;
};
